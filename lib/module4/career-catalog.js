function buildCompetencyProgression(career) {
  const coreSkills = career.skills
    .filter((skill) => skill.importance === "core")
    .map((skill) => skill.name);
  const skills = coreSkills.length ? coreSkills : career.skills.map((skill) => skill.name);
  return {
    beginner: {
      title: "Beginner",
      competencies: skills.slice(0, 2).map((skill) => `Explain the fundamentals of ${skill} and complete a guided exercise.`),
      project: career.projectIdeas[0],
    },
    intermediate: {
      title: "Intermediate",
      competencies: skills.slice(0, 3).map((skill) => `Apply ${skill} independently in a scoped project and document the outcome.`),
      project: career.projectIdeas[1],
    },
    advanced: {
      title: "Advanced",
      competencies: skills.slice(0, 3).map((skill) => `Compare approaches to ${skill}, justify trade-offs, and document validation and risks.`),
      project: career.projectIdeas[2],
    },
  };
}

